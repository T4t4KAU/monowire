"""Contracts between continuous scheduling, tensor transport and model adapters.

A submission returns one completion future per request. Physical batch membership
never determines a request's lifetime. Encoding/decoding are asynchronous and
bounded by active residency; model-specific stream ownership stays in the adapter.
"""

import asyncio
from collections.abc import Callable
from contextlib import AbstractContextManager
from typing import Any, Protocol


class PipelineFailure(RuntimeError):
    """The service cannot accept more work; all owners must drain and stop."""


class RequestAdapter(Protocol):
    async def admit(self, key: str, value: Any) -> Any: ...
    def prepare(self, state: Any) -> Any: ...
    def prepare_batch(self, prepared: list) -> list: ...
    def commit(self, state: Any, prepared: Any, output: Any) -> None: ...
    def finished(self, state: Any) -> bool: ...
    async def finish(self, state: Any) -> Any: ...
    def release(self, state: Any) -> None: ...
    async def close(self) -> None: ...


class BatchExecutor(Protocol):
    def start(
        self, *, on_capacity: Callable[[], None] | None = None
    ) -> asyncio.Future[PipelineFailure]:
        """Listen for service failures, even before the first submission.

        The future resolves to the fatal error; it does not raise or depend on
        request tickets. The executor owns it through close().
        """
        ...

    @property
    def can_submit(self) -> bool:
        """Whether one miss batch can be published without exceeding send capacity."""
        ...

    def submit(self, prepared: list) -> list[asyncio.Future]: ...
    async def close(self) -> None: ...


class StageAdapter(Protocol):
    group: Any

    def validate(self, prepared: list) -> None: ...
    def reuse(self, prepared: list) -> list: ...
    def compute(self, packet: dict) -> dict: ...

    def export_requests(self, prepared: list) -> list[dict]: ...
    def combine_requests(self, items: list[dict]) -> dict: ...


class ModelRuntime(Protocol):
    rank: int
    ingress_replicas: int

    def context(self) -> AbstractContextManager: ...
    def create_adapter(self) -> RequestAdapter: ...
    def create_executor(self) -> BatchExecutor: ...
    def serve(self) -> None: ...
    def close(self) -> None: ...
