"""Contracts between the framework and model integrations.

Prepared payloads and unpack contexts belong to the model. Transport only requires
packets with a nonempty `hidden` tensor; `ticket` and `error` are reserved fields.
An empty hidden tensor is reserved for actor shutdown. pack() executes ingress
model work; compute() executes a downstream stage and updates the packet in place.
"""

from contextlib import AbstractContextManager
from typing import Any, Protocol


class RequestAdapter(Protocol):
    def admit(self, key: str, value: Any) -> Any: ...
    def prepare(self, state: Any) -> Any: ...
    def commit(self, state: Any, prepared: Any, output: Any) -> None: ...
    def finished(self, state: Any) -> bool: ...
    def finish(self, state: Any) -> Any: ...
    def release(self, state: Any) -> None: ...


class BatchExecutor(Protocol):
    async def execute(self, prepared: list) -> list: ...
    async def close(self) -> None: ...


class StageAdapter(Protocol):
    group: Any

    def validate(self, prepared: list) -> None: ...
    def reuse(self, prepared: list) -> list: ...
    def pack(self, prepared: list) -> tuple[dict, Any]: ...
    def compute(self, packet: dict) -> dict: ...
    def unpack(self, output: Any, context: Any) -> list: ...


class ModelRuntime(Protocol):
    rank: int

    def context(self) -> AbstractContextManager: ...
    def create_adapter(self) -> RequestAdapter: ...
    def create_executor(self) -> BatchExecutor: ...
    def serve(self) -> None: ...
    def close(self) -> None: ...
